#!/usr/bin/env node
// Pack a step2mesh export (name.json + name.bin.gz) into a JS module the model imports: the header and the gzipped
// geometry as base64, so the single-file HTML carries the manufacturer's CAD with no fetch.
//   node tools/cadpack.mjs out/name src/model/cad-data.js ["source and licence line"]
// The model then:  import {HEAD, DATA} from './cad-data.js';  import {unpackCad} from '../craft/cad.js';
//                  export const {PARTS, BOXES, part} = await unpackCad(HEAD, DATA);
import fs from 'node:fs';

const [stem, out, note = 'manufacturer CAD'] = process.argv.slice(2);
if (!stem || !out) {
  console.error('usage: node cadpack.mjs <export stem> <out.js> ["source and licence"]');
  process.exit(1);
}
const head = JSON.parse(fs.readFileSync(stem + '.json'));
const gz = fs.readFileSync(stem + '.bin.gz');
const src = `// Generated by craft3d tools/cadpack.mjs from ${note}.
// Tessellated with OpenCascade (tools/step2mesh.py), positions quantised to 0.01 mm, gzip, base64. Do not edit.
export const HEAD = ${JSON.stringify(head)};
export const DATA = '${gz.toString('base64')}';
`;
fs.writeFileSync(out, src);
console.log(`${out}  ${(src.length / 1024).toFixed(0)} KB (${head.parts.length} geometries)`);
